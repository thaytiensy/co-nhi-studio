// Hàm phân tích ngữ nghĩa chủ đề bài học với độ chính xác cao và thứ tự ưu tiên chuẩn xác
export function detectTopicMatch(themeTitle) {
  const t = (themeTitle || '').toLowerCase().trim();

  // Ưu tiên 1: Cụm từ ghép chính xác
  if (t.includes('nón lá') || t.includes('áo dài') || t.includes('trang phục truyền thống')) return ART_TOPIC_KNOWLEDGE_BASE.non_la;
  if (t.includes('trống đồng') || t.includes('đông sơn') || t.includes('chim lạc') || t.includes('đông hồ') || t.includes('di sản')) return ART_TOPIC_KNOWLEDGE_BASE.di_san;
  if (t.includes('đèn lồng') || t.includes('trung thu') || t.includes('ông sao') || t.includes('lễ hội') || t.includes('múa lân') || t.includes('ngày tết')) return ART_TOPIC_KNOWLEDGE_BASE.le_hoi;
  if (t.includes('quê hương') || t.includes('làng quê') || t.includes('đồng lúa') || t.includes('cánh đồng') || t.includes('thôn xóm')) return ART_TOPIC_KNOWLEDGE_BASE.que_huong;
  if (t.includes('đại dương') || t.includes('thủy cung') || t.includes('biển') || t.includes('cá voi') || t.includes('cá heo') || t.includes('con cá') || t.includes('đàn cá')) return ART_TOPIC_KNOWLEDGE_BASE.ca;
  if (t.includes('gà con') || t.includes('gà trống') || t.includes('con gà') || t.includes('đàn gà') || /\bgà\b/i.test(t)) return ART_TOPIC_KNOWLEDGE_BASE.ga;
  if (t.includes('mèo con') || t.includes('con mèo') || t.includes('mèo mướp') || /\bmèo\b/i.test(t)) return ART_TOPIC_KNOWLEDGE_BASE.meo;
  if (t.includes('cánh bướm') || t.includes('con bướm') || t.includes('côn trùng') || t.includes('bọ rùa') || /\bbướm\b/i.test(t)) return ART_TOPIC_KNOWLEDGE_BASE.buom;
  if (t.includes('hoa sen') || t.includes('đầm sen') || t.includes('vườn hoa') || t.includes('bông hoa') || /\bhoa\b/i.test(t)) return ART_TOPIC_KNOWLEDGE_BASE.hoa;
  if (t.includes('trái cây') || t.includes('quả ngọt') || t.includes('đĩa quả') || t.includes('bình hoa và quả') || /\bquả\b/i.test(t)) return ART_TOPIC_KNOWLEDGE_BASE.trai_cay;
  if (t.includes('ô tô') || t.includes('xe tải') || t.includes('xe đạp') || t.includes('thuyền buồm') || t.includes('giao thông') || t.includes('xe cộ') || /\bxe\b/i.test(t)) return ART_TOPIC_KNOWLEDGE_BASE.xe;
  if (t.includes('chân dung') || t.includes('bạn thân') || t.includes('khuôn mặt') || t.includes('bạn bè') || t.includes('thầy cô')) return ART_TOPIC_KNOWLEDGE_BASE.chan_dung;
  if (t.includes('rừng cây') || t.includes('khu rừng') || t.includes('bốn mùa') || t.includes('cây xanh') || /\brừng\b/i.test(t)) return ART_TOPIC_KNOWLEDGE_BASE.rung;
  if (t.includes('ngôi nhà') || t.includes('ngôi trường') || t.includes('trường em') || t.includes('lớp học') || /\bnhà\b/i.test(t)) return ART_TOPIC_KNOWLEDGE_BASE.nha;

  return null;
}

// Helper xáo trộn đáp án ngẫu nhiên để đáp án đúng không phải lúc nào cũng ở vị trí đầu tiên
function shuffleOptions(question) {
  const originalOptions = [...question.options];
  const correctOptionText = originalOptions[question.correctAnswer];

  const shuffled = [...originalOptions];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  const newCorrectIndex = shuffled.indexOf(correctOptionText);
  return {
    ...question,
    options: shuffled,
    correctAnswer: newCorrectIndex >= 0 ? newCorrectIndex : 0
  };
}

